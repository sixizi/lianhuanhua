def emit(story):
    folder = os.path.join(ROOT, '资治通鉴', '%s-%s' % (story['NN'], story['TITLE']))
    os.makedirs(folder, exist_ok=True)
    consts = '\n'.join('%s = %r' % (k, v) for k, v in story['consts'].items())
    scenes = []
    for name, desc, refs in story['scenes']:
        joined = repr(desc) + ''.join(' + ' + r for r in refs) + " + '。' + STYLE + '。' + NOTEXT"
        scenes.append("    (%r,\n     %s)," % (name, joined))
    inscs = []
    for name, cols in story['inscriptions']:
        inner = ',\n                      '.join(repr(c) for c in cols)
        inscs.append("    (%r, [%s])," % (name, inner))
    body = HEADER.format(NN=story['NN'], TITLE=story['TITLE'], JUAN=story['JUAN'],
                         BEATS=story['BEATS'])
    body += consts + '\n\nSCENES = [\n' + '\n'.join(scenes) + '\n]\n\n'
    body += 'INSCRIPTIONS = [\n' + '\n'.join(inscs) + '\n]\n'
    body += FOOTER.format(KEY=story['KEY'])
    # 单引号 repr 处理：中文串安全，仅检查无反斜杠转义
    assert '\\r' not in body and '\\n' not in body
    path = os.path.join(folder, 'gen_batch.py')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(body)
    print('written:', os.path.relpath(path, ROOT), len(body), 'bytes')
    return path


