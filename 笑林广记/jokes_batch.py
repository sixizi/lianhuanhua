def find_base(drafts, sname):
    for ext in ('.jpg', '.jpeg', '.png'):
        p = os.path.join(drafts, sname + '-底图' + ext)
        if os.path.exists(p):
            return p
    return None


def run():
    only = sys.argv[1:]
    ok, fail = [], []

    def wanted(jname, sname):
        if not only:
            return True
        return any(s in jname or s in sname for s in only)

    for jname, scenes in JOKES:
        folder = os.path.join(HERE, jname)
        drafts = os.path.join(folder, 'drafts')
        os.makedirs(drafts, exist_ok=True)
        for sname, prompt, cols in scenes:
            if not wanted(jname, sname):
                continue
            base = find_base(drafts, sname)
            if not base:
                print('=== ' + jname + '/' + sname + ' 底图', flush=True)
                r = subprocess.run([sys.executable, GEN, prompt, '-d', drafts,
                                    '-n', sname + '-底图'])
                print('    exit ' + str(r.returncode), flush=True)
                (ok if r.returncode == 0 else fail).append(
                    jname + '/' + sname + '-底图')
                base = find_base(drafts, sname)
            if not base:
                print('=== ' + jname + '/' + sname + ' 缺底图，跳过合成', flush=True)
                fail.append(jname + '/' + sname + '-合成')
                continue
            print('=== ' + jname + '/' + sname + ' 合成题款', flush=True)
            cmd = [sys.executable, COMPOSE, base,
                   '-o', os.path.join(folder, sname + '.jpg')]
            for c in cols:
                cmd += ['-c', c]
            cmd += ['-s', SEAL]
            if len(cols) >= 4:
                cmd += ['--col-gap', '90']  # 多列长题款收窄列距，控制检查区宽度
            r = subprocess.run(cmd)
            print('    exit ' + str(r.returncode), flush=True)
            (ok if r.returncode == 0 else fail).append(jname + '/' + sname + '-合成')

    print('DONE ok=' + str(len(ok)) + ' fail=' + str(fail), flush=True)
    return 0 if not fail else 1


if __name__ == '__main__':
    sys.exit(run())
