def build():
    for story, scenes in STORIES.items():
        intro, source, notes, trans, jieshuo = NOTES[story]
        lines = []
        lines.append('# 论语连环画 · %s' % story)
        lines.append('')
        lines.append(intro)
        lines.append('')
        lines.append('## 出处')
        lines.append('')
        lines.append(source)
        lines.append('')
        lines.append('## 原文')
        lines.append('')
        lines.append('（据 daizhigev20《论语》底本节录，题款诸句见组画清单）')
        lines.append('')
        lines.append('## 注释')
        lines.append('')
        for n in notes:
            lines.append('- %s' % n)
        lines.append('')
        lines.append('## 白话译文')
        lines.append('')
        for p in trans:
            lines.append(p)
            lines.append('')
        lines.append('## 解说')
        lines.append('')
        for p in jieshuo:
            lines.append(p)
            lines.append('')
        lines.append('## 组画清单')
        lines.append('')
        lines.append('（表中题款原文含标点为引用原文；画中题款依传统惯例无标点，竖排右起）')
        lines.append('')
        lines.append('| 画 | 场景 | 题款原文 | 白话 |')
        lines.append('| --- | --- | --- | --- |')
        for sname, prompt, cols in scenes:
            scene_short = sname.split('-', 1)[1]
            lines.append('| %s.jpg | %s | %s | 见白话译文 |'
                         % (sname, scene_short, ' / '.join(cols)))
        lines.append('')
        out = os.path.join(HERE, '论语', story, '故事.md')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n')
        print('doc', story, len(scenes), '幕')
    print('DONE')


if __name__ == '__main__':
    build()
